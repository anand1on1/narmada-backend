// Sorted, deduped list of ISO 4217 currency codes present in the country table.
export const CURRENCIES: string[] = Array.from(
  new Set(COUNTRIES.map((c) => c.currency)),
).sort();

// Sorted dial-code list (for the standalone country-code picker).
export const DIAL_CODES: { dial: string; label: string }[] = Array.from(
  new Set(COUNTRIES.map((c) => c.dial)),
)
  .sort((a, b) => a.localeCompare(b))
  .map((d) => ({ dial: d, label: d }));

export function findCountry(code: string): Country | undefined {
  return COUNTRIES.find((c) => c.code === code);
}
